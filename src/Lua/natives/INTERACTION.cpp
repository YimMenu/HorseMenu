#include "NativeBinding.hpp"
#include "game/rdr/Natives.hpp"

namespace Terminus::LuaJIT::Natives
{
	static void LUA_NATIVE_INTERACTION_SET_MOUSE_CURSOR_THIS_FRAME()
	{
		INTERACTION::SET_MOUSE_CURSOR_THIS_FRAME();
	}

	static void LUA_NATIVE_INTERACTION_SET_MOUSE_CURSOR_STYLE(int style)
	{
		INTERACTION::SET_MOUSE_CURSOR_STYLE(style);
	}

	static void LUA_NATIVE_INTERACTION__SET_ALLOW_FIRST_PERSON_MOUSE_CAMERA_MOVEMENT()
	{
		INTERACTION::_SET_ALLOW_FIRST_PERSON_MOUSE_CAMERA_MOVEMENT();
	}

	static bool LUA_NATIVE_INTERACTION__POINTER_IS_BEING_MOVED()
	{
		auto retval = (bool)INTERACTION::_POINTER_IS_BEING_MOVED();
		return retval;
	}

	static bool LUA_NATIVE_INTERACTION__POINTER_IS_LEFT_BUTTON_HELD()
	{
		auto retval = (bool)INTERACTION::_POINTER_IS_LEFT_BUTTON_HELD();
		return retval;
	}

	static bool LUA_NATIVE_INTERACTION__POINTER_IS_LEFT_BUTTON_JUST_RELEASED()
	{
		auto retval = (bool)INTERACTION::_POINTER_IS_LEFT_BUTTON_JUST_RELEASED();
		return retval;
	}

	void RegisterNatives_INTERACTION(sol::state& L)
	{
		auto INTERACTION = L["INTERACTION"].get_or_create<sol::table>();
		INTERACTION.set_function("SET_MOUSE_CURSOR_THIS_FRAME", LUA_NATIVE_INTERACTION_SET_MOUSE_CURSOR_THIS_FRAME);
		INTERACTION.set_function("SET_MOUSE_CURSOR_STYLE", LUA_NATIVE_INTERACTION_SET_MOUSE_CURSOR_STYLE);
		INTERACTION.set_function("_SET_ALLOW_FIRST_PERSON_MOUSE_CAMERA_MOVEMENT", LUA_NATIVE_INTERACTION__SET_ALLOW_FIRST_PERSON_MOUSE_CAMERA_MOVEMENT);
		INTERACTION.set_function("_POINTER_IS_BEING_MOVED", LUA_NATIVE_INTERACTION__POINTER_IS_BEING_MOVED);
		INTERACTION.set_function("_POINTER_IS_LEFT_BUTTON_HELD", LUA_NATIVE_INTERACTION__POINTER_IS_LEFT_BUTTON_HELD);
		INTERACTION.set_function("_POINTER_IS_LEFT_BUTTON_JUST_RELEASED", LUA_NATIVE_INTERACTION__POINTER_IS_LEFT_BUTTON_JUST_RELEASED);
	}
}
